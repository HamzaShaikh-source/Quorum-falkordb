"""
The use guide, in one place. guide.json is the single source of truth: the quorum_guide chat tool, GET /api/guide, the console "How to
use Quorum" panel and docs/USER_GUIDE.md (generated by scripts/gen_guide_md.py) all read it, so they cannot drift apart.
"""
import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional

_PATH = Path(__file__).with_name("guide.json")

_ALIASES = {"claude": "claude-code", "claudecode": "claude-code", "copilot": "vscode", "gemini": "antigravity", "agy": "antigravity", "codex": "other", "openai": "chatgpt"}


@lru_cache(maxsize=1)
def load() -> Dict[str, Any]:
    return json.loads(_PATH.read_text(encoding="utf8"))


def topic_ids() -> List[str]:
    return [t["id"] for t in load()["topics"]] + ["install"]


def render_index() -> str:
    g = load()
    lines = [g["intro"], "", "Topics (call quorum_guide(topic='<id>')):"]
    lines += [f"- {t['id']}: {t['title']}. {t['summary']}" for t in g["topics"]]
    lines.append("- install: add the working agreement (and hooks) to this AI. Use quorum_guide(topic='install', client='claude-code'|'cursor'|'vscode'|'windsurf'|'antigravity'|'claude-desktop'|'chatgpt'|'other').")
    lines.append("Start with 'start' if this is a new workspace. The person never needs the console: everything here is done by asking you.")
    return "\n".join(lines)


def render_topic(topic_id: str) -> Optional[str]:
    t = next((x for x in load()["topics"] if x["id"] == topic_id), None)
    if t is None:
        return None
    lines = [f"{t['title']}: {t['summary']}"]
    lines += [f"{i}. {s}" for i, s in enumerate(t["steps"], 1)]
    if t.get("say"):
        lines.append("The person might say: " + " / ".join(f'"{s}"' for s in t["say"]))
    return "\n".join(lines)


def install_plan(client: str) -> Dict[str, Any]:
    g = load()
    key = (client or "other").strip().lower()
    key = _ALIASES.get(key, key)
    c = g["clients"].get(key) or g["clients"]["other"]
    rules = "\n".join(f"{i}. {r}" for i, r in enumerate(g["rules"], 1))
    lines = [
        f"Install plan for {key if key in g['clients'] else 'this AI'}:",
        "1. You are connected (this call proves it). Do not paste or print the token anywhere.",
        f"2. Add this working agreement to {c['file']} (create the file if it does not exist), so every future session follows it:",
        "--- working agreement ---",
        rules,
        "--- end ---",
    ]
    n = 3
    if c["note"]:
        lines.append(f"{n}. {c['note']}")
        n += 1
    if c["hooks"]:
        lines += [
            f"{n}. Optional, Claude Code only. Capture hook: {g['hooks']['capture']}",
            f"   Collision hook: {g['hooks']['conflict']}",
            f"   {g['hooks']['token']}",
        ]
        n += 1
    lines.append(f"{n}. Verify: call quorum_status and tell the person, in two sentences, what you set up and what they can now just ask you to do.")
    return {"client": key, "file": c["file"], "rules": g["rules"], "hooks": c["hooks"], "text": "\n".join(lines)}
